import { createClient } from "@supabase/supabase-js";
import fs from 'fs';
import path from 'path';

export const dynamic = 'force-dynamic';

export async function GET(request) {
  try {
    const supabaseUrl = process.env.NEXT_PUBLIC_SUPABASE_URL;
    const supabaseKey = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

    if (!supabaseUrl || !supabaseKey) {
      console.warn("Supabase credentials missing");
      return Response.json({ error: "Supabase credentials missing" }, { status: 501 });
    }

    const supabase = createClient(supabaseUrl, supabaseKey);
    const { searchParams } = new URL(request.url);
    const season = parseInt(searchParams.get("season") || "2026", 10);
    const event = searchParams.get("event");

    if (!event) {
      return Response.json({ error: "Missing 'event' query param" }, { status: 400 });
    }

    const [predictionsRes, historyRes] = await Promise.all([
      supabase
        .from("predictions")
        .select("*")
        .eq("season", season)
        .eq("event", event)
        .order("win_probability", { ascending: false }),
      supabase
        .from("race_history")
        .select("*")
        .eq("season", season)
        .order("round", { ascending: true }),
    ]);

    if (predictionsRes.error) {
      return Response.json({ error: predictionsRes.error.message, details: predictionsRes.error }, { status: 502 });
    }
    if (historyRes.error) {
      return Response.json({ error: historyRes.error.message, details: historyRes.error }, { status: 503 });
    }

    let predictions = predictionsRes.data || [];
    const history = historyRes.data || [];

    // Find all model versions available for this event
    const modelVersions = [...new Set(predictions.map((p) => p.model_version))];
    
    // Choose which model to display
    let selectedModel = searchParams.get("model");
    if (selectedModel === "rf") {
      selectedModel = modelVersions.find(m => m.startsWith("base_"));
    }
    
    if (!selectedModel || !modelVersions.includes(selectedModel)) {
      if (modelVersions.includes("mae")) {
        selectedModel = "mae";
      } else {
        selectedModel = modelVersions.find(m => m.startsWith("base_")) || modelVersions[0];
      }
    }

    // Filter out other models to prevent duplicated drivers in the UI
    if (selectedModel) {
      predictions = predictions.filter((p) => p.model_version === selectedModel);
      
      history = history.filter((h) => 
        h.model_version === selectedModel || 
        (selectedModel.startsWith("base_") && h.model_version && h.model_version.startsWith("base_"))
      );
    }
    
    // Read season_accuracy and other missing fields from local JSON generated by backend
    let localAccuracy = { top3_pct: 0, races: history.length };
    let featureImportance = [];
    let localHistory = history;
    let sessionsUsed = [];
    let recencyLambda = null;
    try {
        const jsonPath = path.join(process.cwd(), 'public', 'predictions.json');
        const localData = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
        if (localData.season_accuracy) {
            localAccuracy = {
                top3_pct: localData.season_accuracy.top3_pct || 0,
                races: history.length || localData.season_accuracy.races || 0
            };
        }
        if (localData.feature_importance) {
            featureImportance = localData.feature_importance;
        }

        if (localData.history && localData.history.length > 0) {
            localHistory = localData.history;
        }
        if (localData.sessions_used) {
            sessionsUsed = localData.sessions_used;
        }
        if (localData.recency_lambda !== undefined) {
            recencyLambda = localData.recency_lambda;
        }
    } catch (e) {
        console.warn("Could not read local predictions.json, using fallback logic");
        localAccuracy.top3_pct = history.filter((h) => h.top3_hit).length / (history.length || 1);
    }

    return Response.json({
      model_version: selectedModel || "unknown",
      generated_at: predictions[0]?.generated_at || null,
      event,
      season,
      round: predictions[0]?.round || null,
      sessions_used: sessionsUsed,
      season_accuracy: localAccuracy,
      recency_lambda: recencyLambda,
      predictions: predictions.map((p) => ({
        driver: p.driver,
        team: p.team,
        predicted_position: p.predicted_position,
        win_probability: p.win_probability,
        uncertainty: p.uncertainty,
        trend: p.trend || { label: "flat", value: null },
        sessions: p.sessions || {},
        feature_importance: p.feature_importance || [],
      })),
      feature_importance: featureImportance,
      history: localHistory.map((h) => ({
        event: h.event,
        predicted: h.predicted,
        actual: h.actual,
        top3_hit: h.top3_hit,
      })),
    });
  } catch (error) {
    console.error("Unhandled API Error:", error);
    return Response.json({ error: "Unhandled API Error", message: error.message, stack: error.stack }, { status: 504 });
  }
}
